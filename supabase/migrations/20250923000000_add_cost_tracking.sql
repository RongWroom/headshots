-- Adds tables for tracking training costs, estimates, and budget alerts

-- Training costs table: Tracks actual costs for completed training jobs
CREATE TABLE IF NOT EXISTS "public"."training_costs" (
    "id" bigint NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "model_id" bigint NOT NULL,
    "user_id" "uuid" NOT NULL,
    "training_id" "text" NOT NULL,
    "service_provider" "text" NOT NULL DEFAULT 'runpod',
    "gpu_type" "text",
    "training_start_time" timestamp with time zone,
    "training_end_time" timestamp with time zone,
    "training_duration_minutes" integer,
    "gpu_cost_per_hour" decimal(10,4),
    "total_cost" decimal(10,4) NOT NULL,
    "currency" "text" DEFAULT 'USD' NOT NULL,
    "cost_breakdown" jsonb,
    "training_parameters" jsonb,
    "status" "text" DEFAULT 'completed' NOT NULL
);

ALTER TABLE "public"."training_costs" OWNER TO "postgres";

